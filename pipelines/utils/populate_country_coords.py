def run() -> None:
    import os
    # Parse DATABASE_URL from .env.pipeline if not already set
    if not os.environ.get("DATABASE_URL"):
        env_file = Path(__file__).parent.parent.parent / ".env.pipeline"
        if env_file.exists():
            for line in env_file.read_text().splitlines():
                if line.startswith("DATABASE_URL="):
                    os.environ["DATABASE_URL"] = line[len("DATABASE_URL="):]
                    break

    from pipelines.utils.db import fetchall, get_conn

    # Get all countries needing coordinates
    countries = fetchall(
        "SELECT iso3, lat, lng FROM malaria.dim_country ORDER BY iso3"
    )
    print(f"Total countries in dim_country: {len(countries)}")

    missing = [r for r in countries if r["lat"] is None or r["lng"] is None]
    print(f"Missing lat/lng: {len(missing)}")

    updates = []
    not_found = []
    for row in missing:
        iso3 = row["iso3"]
        coords = COUNTRY_CENTROIDS.get(iso3)
        if coords:
            updates.append((coords[0], coords[1], iso3))
        else:
            not_found.append(iso3)

    if not_found:
        print(f"No centroid data for {len(not_found)} codes: {not_found}")

    if not updates:
        print("Nothing to update.")
        return

    conn = get_conn()
    cur = conn.cursor()
    cur.executemany(
        "UPDATE malaria.dim_country SET lat=%s, lng=%s WHERE iso3=%s",
        updates
    )
    conn.commit()
    cur.close()
    conn.close()

    print(f"Updated lat/lng for {len(updates)} countries.")

    # Verify
    still_null = fetchall(
        "SELECT iso3 FROM malaria.dim_country WHERE lat IS NULL OR lng IS NULL"
    )
    print(f"Still NULL after update: {len(still_null)}"
          + (f" — {[r['iso3'] for r in still_null]}" if still_null else ""))


if __name__ == "__main__":
    run()
